test('legacy collection pages are removed and all generated collection links use root routes', () => {
  const routes = read('lib/cms/routes.ts')
  const components = read('lib/cms/components.ts')
  const data = read('data/data.ts')
  const builder = read('app/admin/dashboard/page-builder/page.tsx')
  const newsRail = read('components/home/NewsRail.tsx')
  const gallery = read('components/home/SuccessStoriesGallery.tsx')
  const seed = read('seed-structural.ts')
  assert.match(routes, /'\/what-we-do\/news': '\/news'/)
  assert.match(routes, /'\/what-we-do\/success-stories': '\/success-stories'/)
  assert.match(components, /slug: '\/news', component: 'news'/)
  assert.match(components, /slug: '\/success-stories', component: 'success-story'/)
  assert.doesNotMatch(components, /slug: '\/what-we-do\/(news|success-stories)'/)
  assert.doesNotMatch(data, /^\s*'\/what-we-do\/(news|success-stories)':/m)
  assert.doesNotMatch(data, /href:'\/what-we-do\/(news|success-stories)'/)
  assert.match(builder, /href: '\/news'/)
  assert.match(builder, /href: '\/success-stories'/)
  assert.match(newsRail, /const newsHref = '\/news'/)
  assert.match(gallery, /href="\/success-stories"/)
  assert.match(seed, /CONTENT_COLLECTION_ROUTES\.map\(\(route\) => route\.slug\)/)
})
