test('News and Success Story types have separate immutable collection routes', async () => {
  const componentsSource = read('lib/cms/components.ts')
  const contentSource = read('lib/cms/content.ts')
  const editor = read('app/admin/dashboard/_components/ContentEditor.tsx')
  assert.match(componentsSource, /slug: '\/news', component: 'news'/)
  assert.match(componentsSource, /slug: '\/success-stories', component: 'success-story'/)
  assert.match(componentsSource, /news: '\/news'/)
  assert.match(componentsSource, /'success-story': '\/success-stories'/)
  assert.match(contentSource, /const fixedParent = FIXED_CONTENT_PARENT\[component\]/)
  assert.match(contentSource, /FIXED_CONTENT_PARENT\[component\] \|\| requestedRouteParent/)
  assert.match(contentSource, /detailPath: `\$\{fixedParent\}\/\$\{slug\}`/)
  assert.match(editor, /News articles always publish under the News collection/)
  assert.match(editor, /Success stories always publish under the Success Stories collection/)
})

