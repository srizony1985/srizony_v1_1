import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'

const read = (file: string) => readFileSync(resolve(process.cwd(), file), 'utf8')

test('site content feeds reuse the existing content-type card designs', () => {
  const renderer = read('components/pages/SectionContent.tsx')
  const cards = read('components/pages/ContentFeedCard.tsx')
  const globals = read('app/globals.css')
  const polish = read('app/site-polish.css')
  assert.match(renderer, /<ContentFeedCard key=/)
  assert.match(renderer, /sf-feed-grid/)
  assert.match(cards, /item\.component === 'project'/)
  assert.match(cards, /item\.component === 'notice'/)
  assert.match(cards, /className="carousel-card sf-feed-card--project"/)
  assert.match(cards, /className="notice-card sf-feed-card--notice"/)
  assert.match(cards, /className="sf-feed-card--job"/)
  assert.match(cards, /className="sf-job-feed-card"/)
  assert.match(cards, /carousel-card-body/)
  assert.match(cards, /notice-date/)
  assert.match(cards, /content-card-copy/)
  assert.match(globals, /\.content-card,\s*\.notice-card,\s*\.location-card,\s*\.carousel-card/)
  assert.match(polish, /grid-auto-rows: auto; align-items: start;/)
  assert.match(polish, /\.sf-content-feed \.sf-feed-grid \.carousel-card-body \{ display: flex; flex-direction: column; gap: 4px;/)
  assert.doesNotMatch(cards, /sf-news-card|sf-notice-feed-card|sf-card-body|sf-card-media/)
  const feedCss = polish.slice(polish.indexOf('.sf-content-feed .sf-feed-grid'), polish.indexOf('/* Routed page layout and padding'))
  assert.doesNotMatch(feedCss, /grid-auto-rows: 1fr/)
})

test('content feed columns can be edited in CMS and reach the rendered grid', () => {
  const types = read('types/entityType.ts')
  const editor = read('app/admin/dashboard/page-builder/page.tsx')
  const renderer = read('components/pages/SectionContent.tsx')
  const css = read('app/site-components.css')
  assert.match(types, /type: 'contentFeed'.*columns\?: 2 \| 3 \| 4/)
  assert.match(editor, /Columns \(desktop\)/)
  assert.match(editor, /setConfig\(\{ columns: Number\(event\.target\.value\) as 2 \| 3 \| 4 \}\)/)
  assert.match(renderer, /fixedTwoColumnFeed = feedComponent === 'notice' \|\| feedComponent === 'job'/)
  assert.match(renderer, /feedColumns = fixedTwoColumnFeed \? 2 : collection\?\.columns \?\? desktopColumns/)
  assert.match(renderer, /feedTabletColumns = fixedTwoColumnFeed \? 2 : Math\.min\(collection\?\.columns \?\? tabletColumns, 2\)/)
  assert.match(renderer, /feedGap = fixedTwoColumnFeed \? '18px'/)
  assert.match(css, /repeat\(var\(--cols-tablet, 2\), minmax\(0, 1fr\)\)/)
  assert.match(css, /repeat\(var\(--cols-mobile, 1\), minmax\(0, 1fr\)\)/)
  const polish = read('app/site-polish.css')
  assert.match(polish, /\.sf-content-feed--notice \.sf-feed-grid,[\s\S]*\.sf-content-feed--job \.sf-feed-grid \{[\s\S]*grid-auto-rows: minmax\(224px, 1fr\)/)
})

test('page width and content padding settings are persisted and applied to routed pages', () => {
  const types = read('types/entityType.ts')
  const editor = read('app/admin/dashboard/page-builder/page.tsx')
  const template = read('components/pages/PageTemplate.tsx')
  const css = read('app/site-polish.css')
  assert.match(types, /contentPadding\?: 'none' \| 'compact' \| 'normal' \| 'spacious'/)
  assert.match(editor, /Routed page content padding/)
  assert.match(editor, /updateTop\('contentPadding'/)
  assert.match(template, /sf-page--padding-\$\{page\.contentPadding \|\| 'normal'\}/)
  assert.match(css, /\.sf-page--wide \.sf-page-grid \{ width:/)
  assert.match(css, /\.sf-page--narrow \.sf-page-grid \{ width:/)
  assert.match(css, /\.sf-page--padding-compact \.sf-page-grid \{ padding-block:/)
  assert.match(css, /\.sf-page--padding-spacious \.sf-page-grid \{ padding-block:/)
})

